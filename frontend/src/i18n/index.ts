type MessageTree = Record<string, unknown>

function deepMerge<T extends MessageTree>(base: T, patch: MessageTree): T {
  const out = { ...base } as T
  for (const key of Object.keys(patch)) {
    const pv = patch[key]
    const bv = base[key]
    if (
      pv !== null &&
      typeof pv === 'object' &&
      !Array.isArray(pv) &&
      bv !== null &&
      typeof bv === 'object' &&
      !Array.isArray(bv)
    ) {
      out[key as keyof T] = deepMerge(
        bv as MessageTree,
        pv as MessageTree,
      ) as T[keyof T]
    } else if (pv !== undefined) {
      out[key as keyof T] = pv as T[keyof T]
    }
  }
  return out
}

